"use client";

import React, { useState } from "react";
import { motion, AnimatePresence } from "framer-motion";
import { 
  Globe, Zap, FileText, Smartphone, TrendingUp, Search, 
  CheckCircle2, AlertTriangle, XCircle, ChevronDown, Download, Users, Lightbulb, Target
} from "lucide-react";
import { CircularProgress } from "@/components/ui/circular-progress";
import { ScoreCard } from "./ScoreCard";
import { AIChatPanel } from "./AIChatPanel";
import { Button } from "@/components/ui/button";

interface AuditorDashboardProps {
  data: any;
  onNewAudit: () => void;
}

export function AuditorDashboard({ data, onNewAudit }: AuditorDashboardProps) {
  const [activeTab, setActiveTab] = useState("overview");

  // Fallback data if API doesn't return everything yet
  const overview = data?.overview || {
    domain: data?.domain || "example.com",
    title: "Website Title",
    metaDescription: "No description found.",
    ssl: true,
    cms: "WordPress",
    loadSpeed: "2.4s"
  };

  const scores = data?.scores || {
    overall: 87,
    technical: 92,
    content: 78,
    performance: 85,
    mobile: 95
  };

  const recommendations = data?.recommendations || [
    { priority: "High", title: "Fix missing H1 tags", description: "Several pages are missing H1 tags which impacts SEO." },
    { priority: "High", title: "Optimize homepage speed", description: "LCP is over 2.5s on mobile." },
    { priority: "Medium", title: "Improve internal linking", description: "Orphaned pages detected without incoming links." },
    { priority: "Low", title: "Add FAQ schema", description: "Implement structured data for better rich snippets." }
  ];

  return (
    <div className="w-full max-w-7xl mx-auto space-y-6 pb-20">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-end justify-between gap-4">
        <div>
          <div className="flex items-center gap-3 mb-2">
            <button onClick={onNewAudit} className="text-sm text-gray-500 hover:text-blue-600 transition-colors">
              ← Back to New Audit
            </button>
            <span className="px-2.5 py-0.5 rounded-full bg-green-100 text-green-700 text-xs font-medium flex items-center gap-1.5">
              <span className="w-1.5 h-1.5 bg-green-500 rounded-full"></span> Live
            </span>
          </div>
          <h1 className="text-3xl font-bold text-gray-900 tracking-tight flex items-center gap-2">
            Audit Report: <span className="text-blue-600">{overview.domain}</span>
          </h1>
          <p className="text-gray-500 mt-1">Generated by LeadFlow AI Consultant</p>
        </div>
        <div className="flex gap-2">
          <Button variant="outline" className="gap-2 bg-white">
            <Download className="w-4 h-4" /> Export PDF
          </Button>
          <Button className="gap-2 bg-blue-600 hover:bg-blue-700 text-white">
            <Target className="w-4 h-4" /> Generate Strategy
          </Button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Main Content Area */}
        <div className="lg:col-span-2 space-y-6">
          
          {/* Overall Score */}
          <div className="bg-white border border-gray-200/60 rounded-3xl p-8 flex items-center gap-10">
            <CircularProgress value={scores.overall} size={160} strokeWidth={12} color="auto" />
            <div>
              <h2 className="text-2xl font-bold text-gray-900 mb-2">Excellent Health</h2>
              <p className="text-gray-500 mb-6 max-w-md">Your website has a strong foundation, but we found a few critical opportunities to improve organic traffic and conversion rates.</p>
              
              <div className="grid grid-cols-2 gap-x-8 gap-y-4">
                <div className="flex items-center justify-between border-b border-gray-100 pb-2">
                  <span className="text-sm text-gray-500 flex items-center gap-2"><Zap className="w-4 h-4 text-blue-500"/> Performance</span>
                  <span className="font-semibold">{scores.performance}/100</span>
                </div>
                <div className="flex items-center justify-between border-b border-gray-100 pb-2">
                  <span className="text-sm text-gray-500 flex items-center gap-2"><FileText className="w-4 h-4 text-orange-500"/> Content</span>
                  <span className="font-semibold">{scores.content}/100</span>
                </div>
                <div className="flex items-center justify-between border-b border-gray-100 pb-2">
                  <span className="text-sm text-gray-500 flex items-center gap-2"><Smartphone className="w-4 h-4 text-purple-500"/> Mobile SEO</span>
                  <span className="font-semibold">{scores.mobile}/100</span>
                </div>
                <div className="flex items-center justify-between border-b border-gray-100 pb-2">
                  <span className="text-sm text-gray-500 flex items-center gap-2"><Globe className="w-4 h-4 text-green-500"/> Technical</span>
                  <span className="font-semibold">{scores.technical}/100</span>
                </div>
              </div>
            </div>
          </div>

          {/* Navigation Tabs */}
          <div className="flex gap-2 overflow-x-auto pb-2 scrollbar-hide border-b border-gray-200">
            {["overview", "technical", "content", "performance", "recommendations"].map((tab) => (
              <button
                key={tab}
                onClick={() => setActiveTab(tab)}
                className={`px-4 py-2.5 text-sm font-medium rounded-t-lg capitalize transition-colors relative whitespace-nowrap ${
                  activeTab === tab ? "text-blue-600" : "text-gray-500 hover:text-gray-900"
                }`}
              >
                {tab}
                {activeTab === tab && (
                  <motion.div
                    layoutId="activeTab"
                    className="absolute bottom-0 left-0 right-0 h-0.5 bg-blue-600"
                  />
                )}
              </button>
            ))}
          </div>

          {/* Tab Content */}
          <div className="min-h-[400px]">
            <AnimatePresence mode="wait">
              <motion.div
                key={activeTab}
                initial={{ opacity: 0, y: 10 }}
                animate={{ opacity: 1, y: 0 }}
                exit={{ opacity: 0, y: -10 }}
                transition={{ duration: 0.2 }}
                className="space-y-6"
              >
                {activeTab === "overview" && (
                  <div className="grid grid-cols-2 gap-4">
                    <div className="col-span-2 grid grid-cols-2 md:grid-cols-4 gap-4">
                       <div className="bg-white p-4 rounded-xl border border-gray-200/60 shadow-sm">
                         <p className="text-xs text-gray-500 mb-1">SSL Certificate</p>
                         <p className="font-semibold flex items-center gap-1.5">
                           {overview.ssl ? <CheckCircle2 className="w-4 h-4 text-green-500"/> : <XCircle className="w-4 h-4 text-red-500"/>}
                           {overview.ssl ? "Valid" : "Invalid"}
                         </p>
                       </div>
                       <div className="bg-white p-4 rounded-xl border border-gray-200/60 shadow-sm">
                         <p className="text-xs text-gray-500 mb-1">Detected CMS</p>
                         <p className="font-semibold">{overview.cms}</p>
                       </div>
                       <div className="bg-white p-4 rounded-xl border border-gray-200/60 shadow-sm">
                         <p className="text-xs text-gray-500 mb-1">Load Speed</p>
                         <p className="font-semibold flex items-center gap-1.5">
                           <Zap className="w-4 h-4 text-yellow-500"/> {overview.loadSpeed}
                         </p>
                       </div>
                       <div className="bg-white p-4 rounded-xl border border-gray-200/60 shadow-sm">
                         <p className="text-xs text-gray-500 mb-1">Mobile Friendly</p>
                         <p className="font-semibold flex items-center gap-1.5">
                           <Smartphone className="w-4 h-4 text-blue-500"/> Yes
                         </p>
                       </div>
                    </div>

                    <div className="col-span-2 bg-white rounded-xl border border-gray-200/60 shadow-sm p-6">
                       <h3 className="text-sm font-semibold text-gray-900 mb-4">Meta Information</h3>
                       <div className="space-y-4">
                         <div>
                           <p className="text-xs text-gray-500 mb-1">Title Tag</p>
                           <p className="text-sm font-medium text-gray-900 bg-gray-50 p-2.5 rounded-lg border border-gray-100">{overview.title}</p>
                         </div>
                         <div>
                           <p className="text-xs text-gray-500 mb-1">Meta Description</p>
                           <p className="text-sm font-medium text-gray-900 bg-gray-50 p-2.5 rounded-lg border border-gray-100">{overview.metaDescription}</p>
                         </div>
                       </div>
                    </div>
                  </div>
                )}

                {activeTab === "technical" && (
                   <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                     <ScoreCard title="Indexability" score={98} icon={Search} description="Robots.txt and XML sitemaps configuration." issues={0} warnings={1} passed={12} />
                     <ScoreCard title="Links" score={82} icon={Globe} description="Internal linking structure and broken links." issues={4} warnings={2} passed={45} />
                     <ScoreCard title="Security" score={100} icon={CheckCircle2} description="SSL, HTTPS redirects, and secure headers." issues={0} warnings={0} passed={8} />
                   </div>
                )}

                {activeTab === "recommendations" && (
                  <div className="space-y-4">
                    {recommendations.map((rec: any, idx: number) => (
                      <div key={idx} className="bg-white p-5 rounded-xl border border-gray-200/60 shadow-sm flex items-start gap-4">
                        <div className={`p-2 rounded-lg shrink-0 ${
                          rec.priority === "High" ? "bg-red-50 text-red-600" :
                          rec.priority === "Medium" ? "bg-yellow-50 text-yellow-600" :
                          "bg-blue-50 text-blue-600"
                        }`}>
                          {rec.priority === "High" ? <AlertTriangle className="w-5 h-5"/> : 
                           rec.priority === "Medium" ? <TrendingUp className="w-5 h-5"/> : 
                           <Lightbulb className="w-5 h-5"/>}
                        </div>
                        <div>
                          <div className="flex items-center gap-2 mb-1">
                            <h3 className="font-semibold text-gray-900">{rec.title}</h3>
                            <span className={`text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded-full ${
                              rec.priority === "High" ? "bg-red-100 text-red-700" :
                              rec.priority === "Medium" ? "bg-yellow-100 text-yellow-700" :
                              "bg-blue-100 text-blue-700"
                            }`}>{rec.priority} PRIORITY</span>
                          </div>
                          <p className="text-sm text-gray-500">{rec.description}</p>
                        </div>
                      </div>
                    ))}
                  </div>
                )}
              </motion.div>
            </AnimatePresence>
          </div>
        </div>

        {/* Sidebar / Chat Panel */}
        <div className="lg:col-span-1 h-[800px] sticky top-6">
          <AIChatPanel auditData={data} />
        </div>
      </div>
    </div>
  );
}
